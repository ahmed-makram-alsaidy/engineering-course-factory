// Public surface of @course-factory/workspace (P6.6).
//
// Contracts, reviewed policy, the trusted WorkspaceCoordinator lifecycle,
// the P6.4 confined Windows host file adapter and the P6.6 trusted editor
// admission plus main-owned document registry: workspace protocol DTOs,
// ownership transitions, epoch fencing, reset-order checks, the digest-bound
// reviewed access manifest, the future provider interfaces, the P6.2
// in-memory coordinator (fake epoch seam only), the main-only file adapter
// (read plus staged atomic publication) and the P6.6 frozen editor catalog
// with identifier-only admission into main-owned documents (no execution,
// no persistence bytes, no presentation). No container, presentation or UI
// behavior is exported here. The adapter, the admission sessions and the
// document registry are main-only: renderer and preload code must never
// import them.

