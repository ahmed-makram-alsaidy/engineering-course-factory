// ---------------------------------------------------------------------------
// Bounded replay — snapshot pages (design "Replay and display synchronization":
// "Subscribe before snapshot; buffer arrivals, apply snapshot at snapshot_seq,
// then newer events. Ignore duplicates/replay gaps. Bounded pages and explicit
// snapshot-reset if cursor outside history." and "Snapshot 256 events/
// 256 KiB"). A page is a bounded, strictly ordered slice of the main journal
// after a replay cursor; the page itself is a plain DTO (no provider state).
// ---------------------------------------------------------------------------

/** Bounded page size: at most 256 events per snapshot page. */
export const SNAPSHOT_PAGE_MAX_EVENTS = 256;
/** Bounded page payload: at most 256 KiB of serialized events per page. */
export const SNAPSHOT_PAGE_MAX_BYTES = 262_144;

export const TerminalSnapshotPageSchema = z.strictObject({
  runtime_event_version: z.literal(RUNTIME_EVENT_VERSION),
  session_id: IdentifierSchema,
  generation: z.number().int().min(1),
  /** Replay cursor the page was built from: the page contains events with seq > after_seq. */
  after_seq: z.number().int().min(0),
  /** Last seq included in the page (== after_seq when the page is empty). */
  page_end_seq: z.number().int().min(0),
  /** Journal high-water seq at page-build time (safe next cursor for a follow-up page). */
  journal_high_seq: z.number().int().min(0),
  /**
   * True when the cursor lies OUTSIDE the retained history (a stale future
   * cursor, e.g. from a superseded generation): the caller must reset its
   * view and reapply from page_end_seq. Never silently served from a gap.
   */
  reset: z.boolean(),
  /** Strictly ordered journal events with seq > after_seq (redacted; immutable). */
  events: z.array(RuntimeEventSchema).max(SNAPSHOT_PAGE_MAX_EVENTS),
});
export type TerminalSnapshotPage = z.infer<typeof TerminalSnapshotPageSchema>;

