// P5 Terminal Runtime Protocol — runtime_event_version = 1.
//
// Machine-readable contract between the Teaching IDE / runtime client
// (renderer -> preload -> Electron main) and the Terminal Engine /
// ExecutionProvider (main -> provider -> guest supervisor).
// Canonical architecture: docs/P5-DESIGN-SPEC.md.
//
// Ownership boundaries encoded by this contract:
//   - The renderer is passive. Requests carry identifiers only (1-128 chars,
//     strict keys). There is NO command, environment, cwd, image, mount,
//     stdin, resize or any free-form execution field in this protocol; the
//     authored command lives in validated compiled IR owned by trusted
//     runtime state and never crosses the renderer boundary.
//   - Runtime session identity (session_id + generation) is generated by the
//     engine at runtime, is separate from canonical course/lesson/scene/beat
//     identity, and is never written into compiled IR.
//   - Output channels are exactly stdout | stderr. Runtime diagnostics are
//     separate runtime.* event types, never a third output stream ("Docker
//     diagnostics never become lesson stderr").
//   - Logical process_id only. OS PIDs are runtime-internal and private to
//     the guest supervisor; they appear nowhere in this protocol.
//   - Session events (runtime.*) carry null operation provenance.
//
// This module is contract-only: pure Zod schemas and types. Zero behavior,
// zero I/O, zero process/network access. It may be imported type-only by
// sandboxed renderer code (design: "type-only protocol okay") and directly
// by main-process and guest-supervisor code.

import { z } from "zod";

// ---------------------------------------------------------------------------
// Version — independent runtime event contract version (design: "Independent
// runtime_event_version=1"). Evolves separately from the compiled IR version
// (1.0) and the lesson source schema (1.1); the three contracts never drift.
// ---------------------------------------------------------------------------

export const RUNTIME_EVENT_VERSION = 1;

// ---------------------------------------------------------------------------
// Identifiers — design IPC rule: "identifiers 1-128 chars". Identifier values
// are engine/runtime or authored lesson addresses (course/lesson/scene/beat/
// step/process). No charset restriction: authored beat ids are arbitrary
// non-empty strings and identity must round-trip byte-exactly.
// ---------------------------------------------------------------------------

export const IdentifierSchema = z.string().min(1).max(128);
export type Identifier = z.infer<typeof IdentifierSchema>;

/** Digest-pinned OCI reference form (e.g. an immutable image digest). */
export const DigestSchema = z.string().regex(/^sha256:[0-9a-f]{64}$/);
export type Digest = z.infer<typeof DigestSchema>;

// ---------------------------------------------------------------------------
// Canonical state models.
//
// 1. Process lifecycle (design: "process STARTING/RUNNING/STOPPING/EXITED/
//    DISPOSED") — the lifecycle of one logical process attempt.
// 2. Operation outcome — reuses the canonical architecture execution states
//    (PENDING/RUNNING/PASS/HOLD/FAIL/SKIPPED) with NO enum drift; P5 keeps
//    process lifecycle strictly separate from outcomes.
// 3. Container lifecycle (provider-internal vocabulary; consumed by the
//    DockerSandboxProvider in P5.4): ALLOCATING -> CREATED -> STARTING ->
//    READY -> CLOSING -> REMOVED, uncertainty -> HOLD_CLEANUP.
// ---------------------------------------------------------------------------

export const ProcessStateSchema = z.enum(["STARTING", "RUNNING", "STOPPING", "EXITED", "DISPOSED"]);
export type ProcessState = z.infer<typeof ProcessStateSchema>;

export const OperationOutcomeSchema = z.enum(["PENDING", "RUNNING", "PASS", "HOLD", "FAIL", "SKIPPED"]);
export type OperationOutcome = z.infer<typeof OperationOutcomeSchema>;

/** Terminal (final) outcomes only — the values operation.completed may carry. */
export const FinalOperationOutcomeSchema = z.enum(["PASS", "HOLD", "FAIL", "SKIPPED"]);
export type FinalOperationOutcome = z.infer<typeof FinalOperationOutcomeSchema>;

export const ContainerLifecycleStateSchema = z.enum([
  "ALLOCATING",
  "CREATED",
  "STARTING",
  "READY",
  "CLOSING",
  "REMOVED",
  "HOLD_CLEANUP",
]);
export type ContainerLifecycleState = z.infer<typeof ContainerLifecycleStateSchema>;

// ---------------------------------------------------------------------------
// Stop / close causes.
//
// StopCause: why one process is being stopped (design stop paths: authored
// terminal_stop, operator Stop, foreground/starting cancellation, foreground
// deadline, session teardown).
// CloseCause: why a runtime session is being closed (design: "Reset/switch/
// end/renderer loss/app close/failure/timeout/expiry close session").
// ---------------------------------------------------------------------------

export const StopCauseSchema = z.enum([
  "authored_stop",
  "operator_stop",
  "operation_cancelled",
  "timeout",
  "session_closing",
]);
export type StopCause = z.infer<typeof StopCauseSchema>;

export const CloseCauseSchema = z.enum([
  "reset",
  "lesson_switch",
  "lesson_end",
  "renderer_loss",
  "app_close",
  "failure",
  "timeout",
  "session_expiry",
]);
export type CloseCause = z.infer<typeof CloseCauseSchema>;

/** Cleanup confirmation carried by final results and runtime.closed. */
export const CleanupStatusSchema = z.enum(["confirmed", "unconfirmed"]);
export type CleanupStatus = z.infer<typeof CleanupStatusSchema>;

// ---------------------------------------------------------------------------
// Error model — the exact design taxonomy (docs/P5-DESIGN-SPEC.md, "Error
// Model and Logging") plus the codes the design text names elsewhere
// (INVALID_PROCESS_REFERENCE, PROCESS_NOT_STARTED, PROCESS_EXITED (P5.10
// output waits), UNEXPECTED_DESCENDANTS).
// Each code maps to exactly one outcome category:
//   reject  — invalid request, zero spawn, legitimate work preserved
//   hold    — fail-closed prerequisite/admission/cleanup condition
//   fail    — operation/session fails with the true code, then teardown
//   skipped — cancelled, cleanup confirmed
// ---------------------------------------------------------------------------

export const RuntimeErrorCodeSchema = z.enum([
  // Reject, zero spawn, preserve legitimate work.
  "INVALID_REQUEST",
  "WRONG_OWNER",
  "STALE_SESSION",
  "DUPLICATE_START",
  "INVALID_PROCESS_REFERENCE",
  "PROCESS_NOT_STARTED",
  // P5.10 extension (design "Process-output waits / readiness": "already
  // dead -> PROCESS_EXITED"): a process-output wait cannot be satisfied
  // because its target process is already dead (no marker can arrive).
  // Reject, zero wait; the legitimate background lifetime is untouched.
  "PROCESS_EXITED",
  // HOLD, inspection possible.
  "IR_INVALID",
  "IR_RUNTIME_INCONSISTENT",
  "NOT_AUTHORIZED",
  // Prerequisite HOLD, no host fallback.
  "DOCKER_UNAVAILABLE",
  "WRONG_BACKEND",
  "STORAGE_UNVERIFIED",
  "IMAGE_UNAVAILABLE",
  // HOLD before spawn.
  "WORKSPACE_VIOLATION",
  "UNSUPPORTED_COMMAND_PROFILE",
  // P5.3 extension (documented in docs/P5-IMPLEMENTATION.md): workspace
  // prerequisites cannot be established — missing/invalid configured runtime
  // workspace root, unavailable runtime configuration, session workspace
  // missing. HOLD before spawn, like every workspace condition.
  "WORKSPACE_UNAVAILABLE",
  // P5.3 extension (documented): an explicitly requested host environment
  // variable is not permitted by the environment policy. HOLD before spawn.
  "ENVIRONMENT_POLICY_VIOLATION",
  // FAIL with true code/null, teardown.
  "SPAWN_FAILED",
  "EXIT_CODE_MISMATCH",
  // FAIL, cause latched, teardown.
  "TIMEOUT",
  "OUTPUT_LIMIT",
  "LOG_BACKPRESSURE",
  // FAIL session/reconcile.
  "TRANSPORT_FAILED",
  "PROTOCOL_FAILED",
  "LEASE_EXPIRED",
  "BACKGROUND_EXITED_EARLY",
  "UNEXPECTED_DESCENDANTS",
  // SKIPPED, cleanup confirmed.
  "CANCELLED",
  // HOLD, original cause retained, no new runs.
  "CLEANUP_UNCONFIRMED",
  // HOLD, no later-phase execution.
  "UNSUPPORTED_PHASE",
]);
export type RuntimeErrorCode = z.infer<typeof RuntimeErrorCodeSchema>;

