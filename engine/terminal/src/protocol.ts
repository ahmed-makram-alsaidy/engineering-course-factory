// ---------------------------------------------------------------------------
// Output streams. Exactly stdout | stderr — per-stream identity is mandatory
// ("distinct stdout/stderr … per-stream order"), and there is deliberately NO
// "system"/"runtime" stream value: provider/Docker diagnostics are separate
// runtime.* event types, never lesson stderr.
// ---------------------------------------------------------------------------

export const OutputStreamSchema = z.enum(["stdout", "stderr"]);
export type OutputStream = z.infer<typeof OutputStreamSchema>;

// ---------------------------------------------------------------------------
// Event types — the canonical design event set. Normal foreground trace:
// accepted -> started -> output* -> exited -> completed. Spawn failure:
// accepted -> failed -> completed (no invented start/exit). Timeout:
// accepted -> started/output* -> timeout -> stopping -> final output ->
// exited/stopped -> completed. Session events bracket the runtime itself.
// ---------------------------------------------------------------------------

export const RuntimeEventTypeSchema = z.enum([
  "operation.accepted",
  "process.started",
  "process.output",
  "process.timeout",
  "process.stopping",
  "process.exited",
  "process.stopped",
  "process.failed",
  "operation.completed",
  "runtime.closing",
  "runtime.closed",
  "runtime.failed",
]);
export type RuntimeEventType = z.infer<typeof RuntimeEventTypeSchema>;

