// ---------------------------------------------------------------------------
// Runtime event envelope.
//
// Each event: session_id/generation, strictly increasing main-journal seq,
// host monotonic receipt time, operation/attempt identity, course/lesson/
// scene/beat provenance, process_id (null for the foreground operation's
// implicit process), type and payload.
//
// Hard invariants (enforced below):
//   - runtime.* (session) events carry NULL operation provenance
//     (operation_id === null && attempt_id === null);
//   - operation.* events carry non-null operation_id and attempt_id.
// ---------------------------------------------------------------------------

const EventEnvelopeFields = {
  runtime_event_version: z.literal(RUNTIME_EVENT_VERSION),
  /** Runtime session identity — engine-generated, never lesson source identity. */
  session_id: IdentifierSchema,
  /** Session generation; bumped by reset so old-generation output can never enter a new session. */
  generation: z.number().int().min(1),
  /** Strictly increasing main-journal sequence (assigned by main's journal). */
  seq: z.number().int().min(1),
  /** Host monotonic receipt clock. Never compared against guest monotonic durations. */
  monotonic_ms: z.number().int().min(0),
  operation_id: IdentifierSchema.nullable(),
  attempt_id: IdentifierSchema.nullable(),
  /** Canonical lesson provenance — preserved exactly from the compiled IR. */
  course_id: IdentifierSchema.nullable(),
  lesson_id: IdentifierSchema.nullable(),
  scene_id: IdentifierSchema.nullable(),
  beat_id: IdentifierSchema.nullable(),
  /** Authored logical process id; null for foreground operations ("foreground process_id null"). */
  process_id: IdentifierSchema.nullable(),
  type: RuntimeEventTypeSchema,
};

/** Shared structural validation (payload schema per type + provenance invariants). */
function checkRuntimeEventShape(
  event: { type: RuntimeEventType; payload: unknown; operation_id: Identifier | null; attempt_id: Identifier | null },
  ctx: z.RefinementCtx,
): void {
  // Payload must parse under the schema for this exact type (strict keys).
  const payloadResult = EVENT_PAYLOAD_SCHEMAS[event.type].safeParse(event.payload);
  if (!payloadResult.success) {
    const first = payloadResult.error.issues[0];
    ctx.addIssue({
      code: "custom",
      path: ["payload"],
      message: `[RUNTIME_EVENT_PAYLOAD_INVALID] payload does not satisfy the schema for ${event.type}: ${first?.message ?? "unknown issue"}`,
    });
    return;
  }
  if (event.type.startsWith("runtime.")) {
    if (event.operation_id !== null || event.attempt_id !== null) {
      ctx.addIssue({
        code: "custom",
        message: "[RUNTIME_EVENT_PROVENANCE_INVALID] session events (runtime.*) must use null operation provenance",
      });
    }
    return;
  }
  if (event.type.startsWith("operation.")) {
    if (event.operation_id === null || event.attempt_id === null) {
      ctx.addIssue({
        code: "custom",
        message: "[RUNTIME_EVENT_IDENTITY_INVALID] operation events must carry non-null operation_id and attempt_id",
      });
    }
  }
}

/**
 * P5.6: the provider-level event shape, exactly as the provider emits it —
 * WITHOUT the main-journal `seq` and host receipt `monotonic_ms` (main stamps
 * both when it journals the event). Same structural validation as the full
 * runtime event (payload schema per type + provenance invariants).
 */
export const ProviderEventSchema = z
  .strictObject({
    runtime_event_version: EventEnvelopeFields.runtime_event_version,
    session_id: EventEnvelopeFields.session_id,
    generation: EventEnvelopeFields.generation,
    operation_id: EventEnvelopeFields.operation_id,
    attempt_id: EventEnvelopeFields.attempt_id,
    course_id: EventEnvelopeFields.course_id,
    lesson_id: EventEnvelopeFields.lesson_id,
    scene_id: EventEnvelopeFields.scene_id,
    beat_id: EventEnvelopeFields.beat_id,
    process_id: EventEnvelopeFields.process_id,
    type: EventEnvelopeFields.type,
    payload: z.unknown(),
  })
  .superRefine(checkRuntimeEventShape);

export type ProviderEventDto = z.infer<typeof ProviderEventSchema>;

export const RuntimeEventSchema = z
  .strictObject({
    ...EventEnvelopeFields,
    payload: z.unknown(),
  })
  .superRefine(checkRuntimeEventShape);

export type RuntimeEvent = z.infer<typeof RuntimeEventSchema>;

